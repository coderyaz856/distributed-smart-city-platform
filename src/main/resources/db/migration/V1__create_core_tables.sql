CREATE TABLE sensor_data (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sensor_id VARCHAR(50) NOT NULL,
    type VARCHAR(32) NOT NULL,
    sensor_value DOUBLE PRECISION NOT NULL,
    unit VARCHAR(16),
    location VARCHAR(100),
    timestamp TIMESTAMP NOT NULL
);

CREATE INDEX idx_sensor_data_type_timestamp ON sensor_data (type, timestamp DESC);
CREATE INDEX idx_sensor_data_sensor_timestamp ON sensor_data (sensor_id, timestamp DESC);

CREATE TABLE alerts (
    id VARCHAR(36) PRIMARY KEY,
    sensor_id VARCHAR(50) NOT NULL,
    sensor_type VARCHAR(32) NOT NULL,
    message TEXT,
    severity VARCHAR(10) NOT NULL,
    timestamp TIMESTAMP NOT NULL,
    acknowledged BOOLEAN NOT NULL DEFAULT FALSE
);

CREATE INDEX idx_alerts_type_open_timestamp ON alerts (sensor_type, acknowledged, timestamp DESC);

CREATE TABLE recommendations (
    id VARCHAR(36) PRIMARY KEY,
    resource VARCHAR(32) NOT NULL,
    action TEXT NOT NULL,
    justification TEXT,
    expected_savings DOUBLE PRECISION,
    savings_unit VARCHAR(20),
    timestamp TIMESTAMP NOT NULL,
    implemented BOOLEAN NOT NULL DEFAULT FALSE
);

CREATE INDEX idx_recommendations_resource_open_timestamp
    ON recommendations (resource, implemented, timestamp DESC);
